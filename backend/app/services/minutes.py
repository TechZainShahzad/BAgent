"""Decision Log Keeper / minutes (deterministic): renders a draft record of a meeting from
persisted rows only, for attendees to review and correct. No LLM, so nothing is invented."""

import uuid

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.persistence.models import ConflictRecord, Evidence, Meeting, OpenQuestion, Requirement

GROUPS = [
    ("Confirmed decisions", {"confirmed", "ready_for_delivery", "synced"}),
    ("Captured, not yet confirmed", {"extracted", "under_clarification", "observed"}),
    ("Blocked / rejected / superseded", {"blocked", "rejected", "superseded", "cancelled"}),
]


def render_minutes(session: Session, client_id: uuid.UUID, meeting_id: uuid.UUID) -> str:
    m = session.get(Meeting, meeting_id)
    if m is None or m.client_id != client_id:
        raise LookupError("meeting not found in client scope")
    reqs = list(
        session.scalars(
            select(Requirement)
            .where(Requirement.client_id == client_id, Requirement.meeting_id == meeting_id)
            .order_by(Requirement.created_at)
        )
    )
    lines = [
        f"# Draft minutes: {m.title}",
        "",
        "> DRAFT generated by the BA platform from recorded evidence. Attendees: please review "
        "and send corrections; a correction creates a new version and the original is kept.",
        f"> Source: {m.source}. Status: {m.status}.",
    ]
    if m.degraded_reason:
        lines.append(
            f"> WARNING: capture was degraded ({m.degraded_reason}); content may be incomplete."
        )
    for title, statuses in GROUPS:
        group = [r for r in reqs if r.status in statuses]
        if not group:
            continue
        lines += ["", f"## {title}"]
        for r in group:
            inferred = "" if r.explicit else ", inferred"
            lines.append(f"- **{r.title}** ({r.kind}{inferred}) [{r.status}, v{r.current_version}]")
            lines.append(f"  {r.statement}")
            for e in session.scalars(
                select(Evidence).where(
                    Evidence.requirement_id == r.id, Evidence.client_id == client_id
                )
            ):
                who = e.speaker_label or "unknown speaker"
                ident = "linked" if e.stakeholder_id else "unverified"
                lines.append(f'  - evidence: "{e.quote}" ({who}; identity {ident})')
    qs = list(
        session.scalars(
            select(OpenQuestion).where(
                OpenQuestion.client_id == client_id, OpenQuestion.meeting_id == meeting_id
            )
        )
    )
    if qs:
        lines += ["", "## Open questions"]
        lines += [f"- {'[blocking] ' if q.blocking else ''}{q.question} ({q.status})" for q in qs]
    ids = {r.id for r in reqs}
    conflicts = [
        c
        for c in session.scalars(
            select(ConflictRecord).where(ConflictRecord.client_id == client_id)
        )
        if c.requirement_id in ids
    ]
    if conflicts:
        lines += ["", "## Conflicts needing a decision (never auto-resolved)"]
        lines += [f"- {c.relation}: {c.explanation}" for c in conflicts]
    return "\n".join(lines) + "\n"
